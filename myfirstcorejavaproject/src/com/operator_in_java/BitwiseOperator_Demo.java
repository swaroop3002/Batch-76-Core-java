package com.operator_in_java;

//Bitwise and shift Operators

// [ & | ^ ~ ]

public class BitwiseOperator_Demo {

	public static void main(String[] args) {
		
		System.out.println(" Main method started .....");
		
		System.out.println(71 & 87);
		System.out.println(81 & 99);
		System.out.println(71 & 87);
		System.out.println(95 & 61);
		
		
		System.out.println(99 | 41);
		System.out.println(66 | 80);
		System.out.println(57 ^ 44);
		System.out.println(54 ^ 67);
		System.out.println( ~ 21); // formula for  [ ~ ] is -(n  + 1) ,n means the given value;
		

	}

}
